/** Flat translation keys — pt / en / es */
export type LocaleRecord = Record<string, string>;

function tri(pt: string, en: string, es: string): LocaleRecord {
  return { pt, en, es };
}

/** Build { pt: {k:v}, en: {...}, es: {...} } from key -> {pt,en,es} entries */
export function buildLocaleBundles(entries: Record<string, LocaleRecord>) {
  const pt: Record<string, string> = {};
  const en: Record<string, string> = {};
  const es: Record<string, string> = {};
  for (const [key, loc] of Object.entries(entries)) {
    pt[key] = loc.pt;
    en[key] = loc.en;
    es[key] = loc.es;
  }
  return { pt, en, es };
}

